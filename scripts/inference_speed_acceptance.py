"""Validate real paired inference reports; latency is measured, never a CI claim."""
import argparse
import json
from pathlib import Path


def validate(report):
    required = ('exact_output_parity', 'runtime_parameters_unchanged', 'protected_artifacts_unchanged')
    if any(report.get(key) is not True for key in required):
        raise ValueError('Inference parity and artifact preservation must pass')
    expected = {'short': '4', 'primer': 'READY', 'continuation': '56'}
    rows = report['samples']
    if not rows or {row['engine'] for row in rows} != {'baseline', 'candidate'}:
        raise ValueError('A real paired comparison is required')
    for engine in ('baseline', 'candidate'):
        if {row['case'] for row in rows if row['engine'] == engine} != set(expected):
            raise ValueError('All frozen cases must run on both engines')
    for row in rows:
        if row['response'].strip() != expected[row['case']] or row['usage'].get('model_calls') != 1:
            raise ValueError('Every measured reply must be correct and generated by the model')
        if row['engine'] == 'candidate' and row['case'] == 'continuation':
            baseline = next(item for item in rows if item['engine'] == 'baseline'
                            and item['sample'] == row['sample'] and item['case'] == row['case'])
            if row['usage'].get('reused_input_tokens', 0) <= 0 or row['forward_input_tokens'] >= baseline['forward_input_tokens']:
                raise ValueError('Continuation must reuse actual attention work')
    isolation = report['isolation_and_cancellation']
    if any(isolation[key] != 0 for key in ('other_owner_reused_tokens', 'other_session_reused_tokens', 'anonymous_reused_tokens')):
        raise ValueError('Attention state crossed an identity boundary')
    if isolation['same_owner_reused_tokens'] <= 0 or any(isolation[key] is not True for key in (
            'changed_context_parity', 'cancelled_during_real_forward', 'cancelled_reply_discarded', 'cancelled_cache_discarded')):
        raise ValueError('Context changes and cancellation must be verified')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('report', type=Path)
    args = parser.parse_args()
    validate(json.loads(args.report.read_text()))
    print('Actual inference, paired outputs, reduced forward work, isolation and cancellation passed.')
