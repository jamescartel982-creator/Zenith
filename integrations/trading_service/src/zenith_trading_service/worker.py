"""One owned process executes the real native graph, never a replacement graph."""
import argparse
import json
import os
from pathlib import Path
import sys
import signal
import threading
from zenith_integrations.shared.secrets import read_json,read_private,write_private_new
from .config import TradingConfig
from .contracts import ResearchRequest
from .reports import analysis_report
from . import PIN


def arm_deadline(seconds):
    # Linux/macOS OS timer also expires when the parent service crashes. Windows
    # fallback is cooperative with Python scheduling, not a Job Object sandbox.
    if os.name=='posix':
        signal.signal(signal.SIGALRM,signal.SIG_DFL)
        signal.setitimer(signal.ITIMER_REAL,seconds)
    else:
        timer=threading.Timer(seconds,lambda:os._exit(124));timer.daemon=True;timer.start()


def run(config_path,request_path,output):
    sys.dont_write_bytecode=True
    config=TradingConfig(**read_json(config_path))
    arm_deadline(config.deadline_seconds)
    root=config.verify_source()
    request=ResearchRequest.model_validate(read_json(request_path))
    run_root=Path(output).resolve().parent
    # Input is generated by the service; account paths never come from model text.
    account_root=run_root.parent.parent
    key=read_private(config.inference_key_file,maximum=1024).strip()
    if len(key)<32:
        raise ValueError('A dedicated Zenith inference credential is required')
    os.environ['OPENAI_COMPATIBLE_API_KEY']=key
    os.environ['PYTHON_DOTENV_DISABLED']='1'
    os.environ['TRADINGAGENTS_RESULTS_DIR']=str(run_root/'reports')
    os.environ['TRADINGAGENTS_CACHE_DIR']=str(account_root/'cache')
    os.environ['TRADINGAGENTS_MEMORY_LOG_PATH']=str(account_root/'memory/trading_memory.md')
    sys.path.insert(0,str(root))
    import tradingagents
    if Path(tradingagents.__file__).resolve().parent!=root/'tradingagents':
        raise ValueError('Native import resolved outside the pinned source')
    from tradingagents.default_config import DEFAULT_CONFIG
    native=config.native_config(root,account_root,run_root,DEFAULT_CONFIG)
    if request.operation=='research':
        from tradingagents.graph.trading_graph import TradingAgentsGraph
        from .metrics import NativeMetrics
        metrics=NativeMetrics(run_root/'execution-metrics.json')
        graph=TradingAgentsGraph(selected_analysts=('market','social','news','fundamentals'),config=native,callbacks=[metrics])
        state,signal=graph.propagate(request.tickers[0],request.dates[0],asset_type='stock')
        report=analysis_report(state,signal,request.tickers[0],request.dates[0],key)
        report['execution_metrics']=metrics.snapshot()
    else:
        # Preserve the original dated-decision scorer. It is not an order/fill simulator.
        from tradingagents.backtest import run_backtest,summarize
        from zenith_integrations.shared.redaction import redact
        result=run_backtest(request.tickers,request.dates,native,selected_analysts=('market','social','news','fundamentals'),run_id=run_root.name)
        report={'native_source_pin':PIN,'model':'zenith','operation':'backtest',
            'run_id':result.run_id,'cells_run':result.cells_run,'cells_skipped':result.skipped,
            'failures':[[item[0],item[1],'native_cell_failed'] for item in result.failures],
            'settlement_failures':[[item[0],'native_settlement_failed'] for item in result.settlement_failures],
            'summary':redact(summarize(result).render(),(key,)),
            'workflow_status':'requires_review' if result.failures or result.settlement_failures else 'completed',
            'backtest_kind':'native independent dated decision scoring; no cash/fill simulation',
            'confidence':None,'live_orders_enabled':False,
            'point_in_time':{'all_feed_availability_verified':False,'model_training_knowledge_cutoff_verified':False}}
    config.verify_source()
    write_private_new(output,json.dumps(report,ensure_ascii=False,allow_nan=False)+'\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config',required=True);parser.add_argument('--request',required=True);parser.add_argument('--output',required=True)
    args=parser.parse_args()
    try:
        run(args.config,args.request,args.output)
        return 0
    except Exception as exc:
        # Native exceptions may contain prompts, keys or raw vendor responses.
        diagnostic={'event':'native_worker_failed','error_type':type(exc).__name__}
        try:write_private_new(Path(args.output).parent/'worker-failure.json',json.dumps(diagnostic))
        except (ValueError,OSError):pass
        print(json.dumps(diagnostic),file=sys.stderr)
        return 1


if __name__=='__main__':
    raise SystemExit(main())
